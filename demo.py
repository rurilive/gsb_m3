"""mincircle 的演示脚本。

第一段直接跑基线功能，在一批固定点集上打印最小覆盖圆的圆心与平方半径，
以及几个边界点集的覆盖情况。第二段留给改造后的增量式结构来演示，现在只
有一个占位注释。
"""

from mincircle.circle import brute_min_circle


def show(name, points):
    c = brute_min_circle(points)
    print(name, "->", "cx=", c.cx, "cy=", c.cy, "r2=", c.r2)


def main():
    print("=== 基线：枚举点对与三点求最小覆盖圆 ===")
    show("空点集", [])
    show("单点", [(3, -4)])
    show("两点", [(0, 0), (10, 0)])
    show("三点共线", [(0, 0), (4, 0), (10, 0)])
    show("四点共圆", [(0, 0), (10, 0), (10, 10), (0, 10)])
    show("钝角三角形", [(0, 0), (10, 0), (1, 1)])
    print("=== 全部同点 ===")
    show("同点重复", [(7, 7), (7, 7), (7, 7)])
    c = brute_min_circle([(0, 0), (10, 0), (10, 10), (0, 10)])
    print("圆心 (5, 5) 是否包住 (3, 3)：", c.contains((3, 3)))
    print("圆心 (5, 5) 是否包住 (6, 6)：", c.contains((6, 6)))


