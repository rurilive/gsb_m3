from bitidx.recordset import RecordSet


def main():
    print("=== 朴素全量扫描 ===")
    rs = RecordSet(
        {
            "id": [1, 2, 3, 4, 5, 6],
            "city": [1, 1, 1, 2, 2, 2],
            "tag": [7, 8, 7, 8, 7, 8],
            "amount": [10, 20, 30, 40, 50, 60],
        }
    )
    print("  列 %s，行数 %d" % (rs.column_names, rs.num_rows()))
    print("  city 等于 1 的行号 %s" % (rs.select("city", 1),))
    print("  amount 等于 99 的行号 %s" % (rs.select("amount", 99),))
    print("  第 2 行 %s" % (rs.get_row(2),))

    # TODO(位图索引与位运算查询): 在 bitidx 里补出低基数字段位图、高基数字段分桶位图、
    # 压缩位图、位运算组合查询、计数分页与排序键之后，在这里加一段演示：对同一批条件
    # 分别用逐行扫描与位运算组合查询，打印两边命中的行号集合确认一致；打印低基数列与
    # 稀疏列压缩前后的存储量对比，看压缩比；对一个多条件查询打印命中总数并按行号有序
    # 分页取前几页，再按另一列排序输出前几行；最后插入几行、删掉几行，打印查询结果，
    # 确认位图跟着记录一起更新、没有残留位。


if __name__ == "__main__":
    main()
